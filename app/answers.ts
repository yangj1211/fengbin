export function getAnswer(scene: Scene, preset: number): Answer {
  const variant = variants[scene.id]?.[preset - 1];
  if (!variant) return { ...scene, simple: false };
  const [resultTitle, conclusion, recommendation, items] = variant;
  return {
    resultTitle,
    conclusion,
    recommendation,
    simple: true,
    evidence: items.map((item) => {
      const [title, ...body] = item.split('｜');
      return { title, body: body.join('｜') };
    }),
  };
}
